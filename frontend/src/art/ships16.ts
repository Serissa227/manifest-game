// §6.2 玛雅、§6.3 波利尼西亚）与常见的复原图：
//   galley      加莱桨帆船：长而低，两舷一长排桨，船艏伸出镀金的冲角，前低后高的两面三角帆，船尾一顶红白条纹的篷与大艉灯
//   galiot      加列奥特快船：小一号的桨帆船，单桅三角帆，船尾一顶小篷
//   kobaya      小早：日本的小橹船，舷边一圈矮楯板，艉部几支橹，一面幟（旗指物），水押（艏柱）斜翘，不挂帆
//   sekibune    关船：箱形的楯板墙（矢仓）开一排狭间，单桅草席横帆兼橹，艉部两面幟
//   atakebune   安宅船：通身的黑楯板开两排狭间，船上两层白墙瓦顶的楼阁（矢仓），方头，四面幟，草席帆兼众橹
//   fuchuan     福船：高艏高艉、方艉三重柁楼，两舷护板，两面竹骨硬帆（“帆桅二道”），龙目、木碇、开孔大舵
//   shachuan    沙船：平底低舷、方头方艄（艉部长长的虚艄），四桅硬帆，舷边吊一块披水板
//   niaochuan   鸟船：福建的快船，尖长上翘的艏像鸟喙，龙目上一道绿眉，两面硬帆兼几支桨
//   panokseon   板屋船：平底，下层出桨，上层是外伸的板屋（两排炮眼、女墙），顶上一座红柱瓦顶的将台，两面硬帆
//   jong        爪哇大船：高大的双头船，四桅加一面艏帆都是倾斜的矩形硬帆（tanja，藤席），艉部的舷侧舵，艉上一座棕榈顶的舱屋
//   kora_kora   科拉科拉：长长的独木舟式船体，两头高翘回卷，舷外支架上坐着一排桨手，中部一座草顶，两脚桅挂一面席帆
//   mtepe       姆泰佩：缝合的船板（一排排椰棕针脚），长长前伸的艏喙，一面又高又窄的编席方帆
//   sambuk      桑布克：长斜的艏柱，方艉高起、带窗的艉楼，两面三角帆，白色的船底
//   maya_canoe  玛雅贸易独木舟：长独木舟、两端微翘，中部一座棕榈叶拱篷（篷下货包与陶罐），前后各一排桨手，没有帆
//   balsa_raft  巴尔萨木筏：捆扎的圆木与苇编甲板，几块中插板伸到筏底下，两脚桅挂一面棉布方帆，艉部一间草顶苇屋
//   double_canoe 双体航海独木舟：远近两条船体，中间铺平台、搭草棚，高翘回卷的艉柱，一面蟹爪帆，艉部操舵桨
